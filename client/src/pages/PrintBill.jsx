import { useEffect, useState } from "react";
import { useParams } from "react-router-dom";
import {
  Box,
  Button,
  CircularProgress,
  Alert,
  Typography,
} from "@mui/material";
import PrintRoundedIcon from "@mui/icons-material/PrintRounded";
import { api } from "../api";
import { ThemeProvider } from "@mui/material/styles";
import { buildTheme } from "../theme";

const lightTheme = buildTheme("light");

const p2 = (n) => String(n).padStart(2, "0");
const rs = (n) => `₹ ${Number(n || 0).toFixed(2)}`;

function istParts(date) {
  const ist = new Date(new Date(date).getTime() + 5.5 * 3600 * 1000);
  return {
    date: `${p2(ist.getUTCDate())}/${p2(ist.getUTCMonth() + 1)}/${ist.getUTCFullYear()}`,
    time: `${p2(ist.getUTCHours())}:${p2(ist.getUTCMinutes())}:${p2(ist.getUTCSeconds())} IST`,
  };
}

const th = { padding: "11px 12px", textAlign: "left", fontWeight: 500 };
const td = { padding: "10px 12px" };

export default function PrintBill() {
  const { id } = useParams();
  const [bill, setBill] = useState(null);
  const [error, setError] = useState("");

  useEffect(() => {
    api(`/api/bills/${id}`)
      .then((b) => (b ? setBill(b) : setError("Bill not found.")))
      .catch((e) => setError(e.message));
  }, [id]);

  if (error)
    return (
      <Box sx={{ p: 4 }}>
        <Alert severity="error">{error}</Alert>
      </Box>
    );
  if (!bill)
    return (
      <Box sx={{ display: "grid", placeItems: "center", height: "100vh" }}>
        <CircularProgress />
      </Box>
    );

  const { date, time } = istParts(bill.createdAt);

  return (
    <ThemeProvider theme={lightTheme}>
      <Box
        sx={{
          bgcolor: "#e9eef0",
          minHeight: "100vh",
          py: 4,
          display: "flex",
          flexDirection: "column",
          alignItems: "center",
          "@media print": { bgcolor: "#fff", py: 0 },
        }}
      >
        <Box
          sx={{
            bgcolor: "#fff",
            width: "210mm",
            maxWidth: "100%",
            minHeight: "297mm",
            p: { xs: 2.5, sm: "30px 40px" },
            boxShadow: "0 0 24px rgba(0,0,0,.15)",
            fontSize: 14,
            color: "#111",
            "@media print": { boxShadow: "none", width: "100%", p: "20px" },
          }}
        >
          <Box
            sx={{
              textAlign: "center",
              borderBottom: "3px double #111",
              pb: 2,
              mb: 2.5,
            }}
          >
            <img
              src="/logo.png"
              alt="Logo"
              style={{ width: 90, height: 90, objectFit: "contain" }}
            />
            <Typography variant="h5" sx={{ fontSize: 22 }}>
              Shri Ram Chandra Prasad Care &amp; Cure Clinic
            </Typography>
            <Typography variant="body2" color="text.secondary" sx={{ mt: 0.5 }}>
              Clinic Management System
            </Typography>
            <Typography variant="body2" color="text.secondary">
              Contact: +91 99848-42186
            </Typography>
          </Box>

          <Box
            sx={{
              display: "flex",
              justifyContent: "space-between",
              flexWrap: "wrap",
              gap: 2,
              bgcolor: "#f4f8f8",
              borderRadius: 2,
              p: "14px 18px",
              mb: 2.5,
              lineHeight: 2,
            }}
          >
            <div>
              <div>
                <b>Patient Name:</b> {bill.patientName}
              </div>
              <div>
                <b>Age:</b> {bill.patientAge} years
              </div>
              {bill.patientGender && (
                <div>
                  <b>Gender:</b> {bill.patientGender}
                </div>
              )}
              {bill.patientPhone && (
                <div>
                  <b>Phone:</b> {bill.patientPhone}
                </div>
              )}
            </div>
            <Box sx={{ textAlign: { sm: "right" } }}>
              <div>
                <b>Bill No:</b> #{bill.billNo}
              </div>
              <div>
                <b>Date:</b> {date}
              </div>
              <div>
                <b>Time:</b> {time}
              </div>
              <div>
                <b>Generated By:</b> {bill.generatedBy}
              </div>
            </Box>
          </Box>

          <table
            style={{
              width: "100%",
              borderCollapse: "collapse",
              marginBottom: 20,
            }}
          >
            <thead>
              <tr style={{ background: "#0b3d3b", color: "#fff" }}>
                <th style={th}>#</th>
                <th style={th}>Medicine</th>
                <th style={th}>Tablets</th>
                <th style={th}>Price / Tablet</th>
                <th style={{ ...th, textAlign: "right" }}>Amount</th>
              </tr>
            </thead>
            <tbody>
              {bill.items.map((it, i) => (
                <tr
                  key={i}
                  style={{
                    borderBottom: "1px solid #eee",
                    background: i % 2 ? "#f9fbfb" : "#fff",
                  }}
                >
                  <td style={td}>{i + 1}</td>
                  <td style={td}>{it.name}</td>
                  <td style={td}>{it.tablets}</td>
                  <td style={td}>{rs(it.pricePerTablet)}</td>
                  <td style={{ ...td, textAlign: "right", fontWeight: 600 }}>
                    {rs(it.total)}
                  </td>
                </tr>
              ))}
            </tbody>
          </table>

          <Box sx={{ display: "flex", justifyContent: "flex-end", mb: 4 }}>
            <Box
              sx={{
                display: "flex",
                justifyContent: "space-between",
                gap: 4,
                minWidth: 240,
                bgcolor: "#0b3d3b",
                color: "#fff",
                p: "12px 16px",
                borderRadius: 1,
                fontWeight: 700,
                fontSize: 16,
              }}
            >
              <span>Grand Total</span>
              <span>{rs(bill.grandTotal)}</span>
            </Box>
          </Box>

          <Box
            sx={{
              borderTop: "1px solid #ccc",
              pt: 2.5,
              display: "flex",
              justifyContent: "space-between",
              alignItems: "flex-end",
              fontSize: 13,
              color: "#666",
            }}
          >
            <div>
              <p>Generated by Care &amp; Cure System</p>
              <p>This is a computer generated bill.</p>
            </div>
            <div style={{ textAlign: "center" }}>
              <div
                style={{
                  width: 160,
                  borderTop: "1px solid #333",
                  margin: "50px auto 6px",
                }}
              />
              <p>Authorised Signature</p>
            </div>
          </Box>
          <p
            style={{
              textAlign: "center",
              marginTop: 28,
              fontSize: 13,
              color: "#999",
              fontStyle: "italic",
              paddingTop: 16,
              borderTop: "1px dashed #ddd",
            }}
          >
            Thank you for visiting Care &amp; Cure. Get well soon! 💊
          </p>
        </Box>

        <Button
          variant="contained"
          size="large"
          startIcon={<PrintRoundedIcon />}
          onClick={() => window.print()}
          sx={{ mt: 3, "@media print": { display: "none" } }}
        >
          Print bill
        </Button>
      </Box>
    </ThemeProvider>
  );
}
